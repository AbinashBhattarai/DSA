//Question: Check if the number is Even or Odd

public class OddEven
{
    public static void main(String[] args)
    {
        int number = 9;

        if(number % 2 == 0)
        {
            System.out.println("The Given Number is Even.");
        }
        else
        {
            System.out.println("The Given Number is Odd.");
        }
    }
}

